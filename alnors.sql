

CREATE SEQUENCE SEQ_PRODUCTS      START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CUSTOMERS     START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INVOICES      START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INVOICE_ITEMS START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE CUSTOMERS(
    CUSTOMER_ID NUMBER(10) CONSTRAINT PK_CUSTOMERS PRIMARY KEY,
    CUSTOMER_NAME NVARCHAR2(100) NOT NULL,
    PHONE        NVARCHAR2(20),
    ADDRESS      NVARCHAR2(20)
);

CREATE TABLE PRODUCTS(
    PRODUCT_ID NUMBER(10) CONSTRAINT pk_PRODUCTS PRIMARY KEY,
    PRODUCT_NAME NVARCHAR2(100) NOT NULL CONSTRAINT UQ_PRODUCT_NAME UNIQUE,
    CARTON_PRICE NUMBER(10,2) NOT NULL CONSTRAINT CK_CARTON_PRICE CHECK (CARTON_PRICE > 0),
    QUANTITY NUMBER(8) DEFAULT 0 NOT NULL CONSTRAINT CK_PRODUCT_QTY CHECK (QUANTITY >= 0)
);

CREATE TABLE INVOICES (
    INVOICE_ID NUMBER(10) CONSTRAINT PK_INVOICES PRIMARY KEY,
    CUSTOMER_ID NUMBER(10) NOT NULL CONSTRAINT FK_INV_CUSTOMER REFERENCES CUSTOMERS (CUSTOMER_ID),
    INVOICE_DATE DATE DEFAULT SYSDATE NOT NULL,
    TOTAL_AMOUNT NUMBER(12,2) DEFAULT 0 NOT NULL
);

CREATE TABLE INVOICE_ITEMS (
    ITEM_ID NUMBER(10) CONSTRAINT PK_INVOICE_ITEMS PRIMARY KEY,
    INVOICE_ID NUMBER(10) NOT NULL CONSTRAINT FK_ITEM_INVOICE REFERENCES INVOICES(INVOICE_ID) ON DELETE CASCADE,
    PRODUCT_ID  NUMBER(10) NOT NULL CONSTRAINT FK_ITEM_PRODUCT REFERENCES PRODUCTS(PRODUCT_ID),
    QUANTITY   NUMBER(8) NOT NULL CONSTRAINT CK_ITEM_QTY CHECK (QUANTITY > 0),
    CARTON_PRICE NUMBER(10,2) NOT NULL,
    LINE_TOTAL   NUMBER(12,2) NOT NULL
);

CREATE INDEX IX_INVOICES_CUSTOMER ON INVOICES(CUSTOMER_ID);
CREATE INDEX IX_ITEMS_INVOICE     ON INVOICE_ITEMS(INVOICE_ID);
CREATE INDEX IX_ITEMS_PRODUCT     ON INVOICE_ITEMS(PRODUCT_ID);


